def interleaved() -> list[str]:
    """갈래를 번갈아 낸 질문 목록."""
    buckets: list[list[str]] = [
        list(v) for v in (*ANSWERABLE.values(), *UNSUPPORTED.values(), *JUNK.values())
    ]

    ordered: list[str] = []
    index = 0
    while any(index < len(b) for b in buckets):
        for bucket in buckets:
            if index < len(bucket):
                ordered.append(bucket[index])
        index += 1
    return ordered


def summary() -> str:
    answerable = sum(len(v) for v in ANSWERABLE.values())
    unsupported = sum(len(v) for v in UNSUPPORTED.values())
    junk = sum(len(v) for v in JUNK.values())
    return (
        f"근거 있음 {len(ANSWERABLE)}주제 {answerable}건 · "
        f"근거 없음 {len(UNSUPPORTED)}주제 {unsupported}건 · "
        f"버려질 것 {len(JUNK)}주제 {junk}건 · 합계 {answerable + unsupported + junk}건"
    )
